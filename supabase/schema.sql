-- ---------- Tables ---------------------------------------------------

create type song_kind as enum ('OP', 'ED', 'INSERT');

-- One row per rating "column" (the 16 people from your sheet + any new ones).
-- user_id is filled when a real website account is linked to that column.
create table public.raters (
  id         smallint generated by default as identity primary key,
  name       text not null unique,
  position   smallint not null default 0,
  user_id    uuid unique references auth.users (id) on delete set null
);

-- One row per website account (created automatically on sign-up).
create table public.profiles (
  id         uuid primary key references auth.users (id) on delete cascade,
  email      text,
  username   text,
  is_admin   boolean not null default false,
  created_at timestamptz not null default now()
);

-- One row per song: an Opening, an Ending or an Insert.
--   OP / ED : title = anime name (e.g. "Bleach [OP9]")
--   INSERT  : title = anime, author = artist, song = song name
create table public.songs (
  id          bigint generated by default as identity primary key,
  kind        song_kind not null,
  title       text not null,
  author      text,
  song        text,
  youtube_url text,
  vlink_url   text,
  created_at  timestamptz not null default now()
);
create index songs_kind_idx on public.songs (kind, id);

-- One row per (song, person) score.  Empty cell in the sheet = no row.
create table public.scores (
  song_id    bigint   not null references public.songs (id)  on delete cascade,
  rater_id   smallint not null references public.raters (id) on delete cascade,
  score      numeric(3,1) not null check (score >= 0 and score <= 10),
  updated_at timestamptz not null default now(),
  primary key (song_id, rater_id)
);

-- ---------- Helper: is the current user an admin? --------------------
-- SECURITY DEFINER so it can read profiles without hitting RLS recursion.

create or replace function public.is_admin()
returns boolean
language sql
security definer
stable
set search_path = public
as $$
  select coalesce((select is_admin from public.profiles where id = auth.uid()), false);
$$;

-- ---------- Auto-create a profile on sign-up -------------------------

create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  insert into public.profiles (id, email, username)
  values (new.id, new.email, new.raw_user_meta_data ->> 'username');
  return new;
end;
$$;

create trigger on_auth_user_created
  after insert on auth.users
  for each row execute function public.handle_new_user();

-- ---------- Row Level Security --------------------------------------

alter table public.raters   enable row level security;
alter table public.profiles enable row level security;
alter table public.songs    enable row level security;
alter table public.scores   enable row level security;

-- SONGS: everyone can read, only admins can add / edit / remove
create policy "songs readable by all"  on public.songs for select using (true);
create policy "songs insert admin"     on public.songs for insert with check (public.is_admin());
create policy "songs update admin"     on public.songs for update using (public.is_admin());
create policy "songs delete admin"     on public.songs for delete using (public.is_admin());

-- RATERS: everyone can read, only admins can change (link accounts, add columns)
create policy "raters readable by all" on public.raters for select using (true);
create policy "raters insert admin"    on public.raters for insert with check (public.is_admin());
create policy "raters update admin"    on public.raters for update using (public.is_admin());
create policy "raters delete admin"    on public.raters for delete using (public.is_admin());

-- PROFILES: you see your own, admins see everyone; only admins can edit
-- (so nobody can make themselves admin)
create policy "profiles read own or admin" on public.profiles for select
  using (id = auth.uid() or public.is_admin());
create policy "profiles update admin"      on public.profiles for update
  using (public.is_admin());

-- SCORES: everyone can read.
-- Write: only on YOUR OWN rater column, unless you are an admin.
create policy "scores readable by all" on public.scores for select using (true);

create policy "scores insert own or admin" on public.scores for insert
  with check (
    public.is_admin()
    or rater_id in (select id from public.raters where user_id = auth.uid())
  );

create policy "scores update own or admin" on public.scores for update
  using (
    public.is_admin()
    or rater_id in (select id from public.raters where user_id = auth.uid())
  )
  with check (
    public.is_admin()
    or rater_id in (select id from public.raters where user_id = auth.uid())
  );

create policy "scores delete own or admin" on public.scores for delete
  using (
    public.is_admin()
    or rater_id in (select id from public.raters where user_id = auth.uid())
  );
