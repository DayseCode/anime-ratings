-- =====================================================================
--  Change log (audit log) for admins
--  Run ONCE: Supabase -> SQL Editor -> New query -> paste -> Run
--  Safe to run again (it replaces the functions/triggers).
-- =====================================================================

create table if not exists public.audit_log (
  id       bigint generated by default as identity primary key,
  at       timestamptz not null default now(),
  actor_id uuid,
  actor    text not null default 'system',
  entity   text not null check (entity in ('song', 'score', 'rater', 'profile')),
  action   text not null check (action in ('insert', 'update', 'delete')),
  summary  text not null,
  details  jsonb
);
create index if not exists audit_log_entity_idx on public.audit_log (entity, id desc);

alter table public.audit_log enable row level security;

-- Only admins can read the log. Nobody can write to it from the website:
-- rows are created exclusively by the database triggers below.
drop policy if exists "audit readable by admins" on public.audit_log;
create policy "audit readable by admins" on public.audit_log
  for select using (public.is_admin());

revoke insert, update, delete on public.audit_log from anon, authenticated;

-- ---------- helpers --------------------------------------------------

create or replace function public.audit_actor()
returns text
language sql
security definer
stable
set search_path = public
as $$
  select coalesce(
    (select case when coalesce(p.username, '') <> ''
                 then p.username || ' (' || p.email || ')'
                 else p.email end
       from public.profiles p where p.id = auth.uid()),
    'system');
$$;

create or replace function public.audit_write(_entity text, _action text, _summary text, _details jsonb default null)
returns void
language sql
security definer
set search_path = public
as $$
  insert into public.audit_log (actor_id, actor, entity, action, summary, details)
  values (auth.uid(), public.audit_actor(), _entity, _action, _summary, _details);
$$;

-- these must not be callable from the website (otherwise anyone could forge log lines)
revoke execute on function public.audit_actor() from public, anon, authenticated;
revoke execute on function public.audit_write(text, text, text, jsonb) from public, anon, authenticated;

-- ---------- songs ----------------------------------------------------

create or replace function public.log_song_change()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  changes text[] := '{}';
begin
  if tg_op = 'INSERT' then
    perform public.audit_write('song', 'insert',
      format('Added %s "%s"%s', new.kind, new.title, case when new.song is not null then ' - ' || new.song else '' end),
      to_jsonb(new));
    return new;

  elsif tg_op = 'UPDATE' then
    if new.title       is distinct from old.title       then changes := changes || format('title: "%s" -> "%s"', old.title, new.title); end if;
    if new.author      is distinct from old.author      then changes := changes || format('author: "%s" -> "%s"', coalesce(old.author, '—'), coalesce(new.author, '—')); end if;
    if new.song        is distinct from old.song        then changes := changes || format('song: "%s" -> "%s"', coalesce(old.song, '—'), coalesce(new.song, '—')); end if;
    if new.youtube_url is distinct from old.youtube_url then changes := changes || format('YouTube link: %s -> %s', coalesce(old.youtube_url, '—'), coalesce(new.youtube_url, '—')); end if;
    if new.vlink_url   is distinct from old.vlink_url   then changes := changes || format('VLINK: %s -> %s', coalesce(old.vlink_url, '—'), coalesce(new.vlink_url, '—')); end if;
    if new.kind        is distinct from old.kind        then changes := changes || format('type: %s -> %s', old.kind, new.kind); end if;
    if array_length(changes, 1) is null then return new; end if;
    perform public.audit_write('song', 'update',
      format('Edited %s "%s": %s', old.kind, old.title, array_to_string(changes, '; ')),
      jsonb_build_object('old', to_jsonb(old), 'new', to_jsonb(new)));
    return new;

  else -- DELETE (BEFORE trigger, so the scores still exist and can be saved in the log)
    perform public.audit_write('song', 'delete',
      format('Deleted %s "%s"%s', old.kind, old.title, case when old.song is not null then ' - ' || old.song else '' end),
      jsonb_build_object(
        'song', to_jsonb(old),
        'scores', (select coalesce(jsonb_agg(jsonb_build_object('rater', r.name, 'score', s.score)), '[]'::jsonb)
                     from public.scores s join public.raters r on r.id = s.rater_id
                    where s.song_id = old.id)));
    return old;
  end if;
end;
$$;

drop trigger if exists songs_audit_write  on public.songs;
drop trigger if exists songs_audit_delete on public.songs;
create trigger songs_audit_write  after insert or update on public.songs for each row execute function public.log_song_change();
create trigger songs_audit_delete before delete          on public.songs for each row execute function public.log_song_change();

-- ---------- scores ---------------------------------------------------

create or replace function public.log_score_change()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  sid bigint; rid smallint; oldv numeric; newv numeric;
  t text; k song_kind; rname text;
begin
  if tg_op = 'DELETE' then
    sid := old.song_id; rid := old.rater_id; oldv := old.score;
  elsif tg_op = 'UPDATE' then
    if new.score is not distinct from old.score then return null; end if;
    sid := new.song_id; rid := new.rater_id; oldv := old.score; newv := new.score;
  else
    sid := new.song_id; rid := new.rater_id; newv := new.score;
  end if;

  select title, kind into t, k from public.songs  where id = sid;
  select name       into rname from public.raters where id = rid;
  -- song or column was deleted too (cascade): that deletion is logged on its own
  if t is null or rname is null then return null; end if;

  perform public.audit_write('score', lower(tg_op),
    format('%s: %s -> %s on %s "%s"', rname, coalesce(oldv::text, '—'), coalesce(newv::text, '—'), k, t),
    jsonb_build_object('song_id', sid, 'rater_id', rid, 'old', oldv, 'new', newv));
  return null;
end;
$$;

drop trigger if exists scores_audit on public.scores;
create trigger scores_audit after insert or update or delete on public.scores
  for each row execute function public.log_score_change();

-- ---------- raters (rating columns) ---------------------------------

create or replace function public.log_rater_change()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  who text;
begin
  if tg_op = 'INSERT' then
    perform public.audit_write('rater', 'insert', format('Added rating column "%s"', new.name), to_jsonb(new));
    return new;

  elsif tg_op = 'UPDATE' then
    if new.name is distinct from old.name then
      perform public.audit_write('rater', 'update', format('Renamed column "%s" -> "%s"', old.name, new.name));
    end if;
    if new.user_id is distinct from old.user_id then
      if new.user_id is null then
        perform public.audit_write('rater', 'update', format('Column "%s" unlinked from its account', new.name));
      else
        select coalesce(email, new.user_id::text) into who from public.profiles where id = new.user_id;
        perform public.audit_write('rater', 'update', format('Column "%s" linked to %s', new.name, who));
      end if;
    end if;
    return new;

  else -- DELETE
    perform public.audit_write('rater', 'delete', format('Deleted rating column "%s"', old.name), to_jsonb(old));
    return old;
  end if;
end;
$$;

drop trigger if exists raters_audit_write  on public.raters;
drop trigger if exists raters_audit_delete on public.raters;
create trigger raters_audit_write  after insert or update on public.raters for each row execute function public.log_rater_change();
create trigger raters_audit_delete before delete          on public.raters for each row execute function public.log_rater_change();

-- ---------- profiles (accounts, admin rights) -----------------------

create or replace function public.log_profile_change()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  if tg_op = 'INSERT' then
    insert into public.audit_log (actor_id, actor, entity, action, summary)
    values (new.id, coalesce(nullif(new.username, ''), new.email), 'profile', 'insert',
            format('New account: %s%s', new.email, case when coalesce(new.username, '') <> '' then ' (' || new.username || ')' else '' end));
  elsif new.is_admin is distinct from old.is_admin then
    perform public.audit_write('profile', 'update',
      format('%s %s', new.email, case when new.is_admin then 'was made an admin' else 'is no longer an admin' end));
  end if;
  return null;
end;
$$;

drop trigger if exists profiles_audit on public.profiles;
create trigger profiles_audit after insert or update on public.profiles
  for each row execute function public.log_profile_change();
